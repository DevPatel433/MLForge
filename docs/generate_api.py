"""Generate docs/api.md from the code's own signatures and docstrings.

    python docs/generate_api.py

Run by CI (``make docs``) so the API reference can never drift from the code.
"""
import importlib
import inspect
import os

MODULES = [
    ("Linear models", "mlforge.linear_model"), ("Trees & ensembles", "mlforge.tree"),
    ("Neighbors", "mlforge.neighbors"), ("Clustering", "mlforge.cluster"),
    ("Decomposition", "mlforge.decomposition"), ("Naive Bayes", "mlforge.bayes"),
    ("Support vector machines", "mlforge.svm"), ("Neural networks", "mlforge.neural_network"),
    ("Optimization", "mlforge.optimization"), ("Preprocessing", "mlforge.preprocessing"),
    ("Model selection", "mlforge.model_selection"), ("Metrics", "mlforge.metrics"),
    ("Datasets", "mlforge.datasets"), ("Autograd", "mlforge.autograd"),
    ("Utilities", "mlforge.utils"), ("Visualization", "mlforge.visualization"),
]


def first_paragraph(obj):
    doc = inspect.getdoc(obj) or ""
    return doc.split("\n\n")[0].replace("\n", " ").strip()


def signature(obj):
    try:
        return str(inspect.signature(obj))
    except (TypeError, ValueError):
        return "(...)"


def public_methods(cls):
    names = []
    for n, _ in inspect.getmembers(cls, inspect.isfunction):
        if not n.startswith("_"):
            names.append(n)
    return names


def main(out=None):
    out = out or os.path.join(os.path.dirname(__file__), "api.md")
    lines = ["# API reference", "",
             "_Generated by `docs/generate_api.py` from the source code - do not edit by hand._", ""]
    for title, modname in MODULES:
        mod = importlib.import_module(modname)
        names = getattr(mod, "__all__", [n for n in dir(mod) if not n.startswith("_")])
        lines += [f"## {title}  (`{modname}`)", ""]
        for n in sorted(names):
            obj = getattr(mod, n, None)
            if obj is None or inspect.ismodule(obj):
                continue
            if inspect.isclass(obj):
                lines.append(f"### `class {n}{signature(obj)}`")
                doc = first_paragraph(obj)
                if doc:
                    lines += ["", doc]
                methods = public_methods(obj)
                if methods:
                    lines += ["", "Methods: " + ", ".join(f"`{m}`" for m in methods)]
                lines.append("")
            elif callable(obj):
                lines.append(f"### `{n}{signature(obj)}`")
                doc = first_paragraph(obj)
                if doc:
                    lines += ["", doc]
                lines.append("")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    return out


if __name__ == "__main__":
    print("written", main())
